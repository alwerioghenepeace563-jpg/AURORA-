import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
const root = process.cwd();
const map = fs.readFileSync(path.join(root, "src/MapsWorkspace.jsx"), "utf8");
const css = fs.readFileSync(path.join(root, "src/maps.css"), "utf8");
const app = fs.readFileSync(path.join(root, "src/App.jsx"), "utf8");
assert.match(app, /import MapsWorkspace from "\.\/MapsWorkspace"/, "the existing Maps workspace remains the app map entry point");
assert.match(map, /maplibre-gl@5\.6\.2/, "MapLibre GL engine must load");
assert.match(map, /projection:\s*"globe"/, "the actual map must open in 3D globe projection");
assert.match(map, /tile\.openstreetmap\.org\//, "real street map tiles must be available");
assert.match(map, /World_Imagery\/MapServer\/tile/, "real satellite imagery tiles must be available");
assert.match(map, /nominatim\.openstreetmap\.org\/search/, "place search must use real geocoding");
assert.match(map, /router\.project-osrm\.org\/route/, "road route geometry must be requested");
assert.match(map, /addLayer\(\{ id: "aurora-route-line"/, "road routes must render on the globe map");
assert.match(map, /navigator\.geolocation\.getCurrentPosition/, "one-shot GPS location must be available");
assert.match(map, /navigator\.geolocation\.watchPosition/, "foreground live GPS tracking must be available");
assert.match(map, /map\.setFog\(/, "the globe must have a space atmosphere");
assert.match(map, /resetEarth/, "users must be able to return to the whole-Earth view");
assert.match(css, /\.maps-globe-map/, "the globe map surface must have layout styling");
assert.match(css, /\.maps-earth-shell/, "the map and holographic controls must have responsive layout styling");
assert.doesNotMatch(map, /loadLeaflet|L\.map\(/, "the primary map must no longer fall back to a flat Leaflet-only map");
console.log("AURORA 3D Earth + real map tests passed.");
