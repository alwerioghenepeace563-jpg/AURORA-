const assert = require("node:assert/strict");
(async () => {
 const {createAuroraCreativeUniverse,parseSubtitles,renderSubtitles}=await import("../src/core/aurora-creative-universe.js");
 const values=new Map(),storage={getItem:k=>values.get(k)??null,setItem:(k,v)=>values.set(k,v),removeItem:k=>values.delete(k)};
 let id=0,tick=0;
 const creative=createAuroraCreativeUniverse({storage,createId:p=>p+"-"+(++id),now:()=>new Date(1762646400000+tick++*1000).toISOString()});
 assert.throws(()=>creative.createProject({title:"Short film",type:"video"}),/approval/i);
 const project=creative.createProject({title:"Science explainer",type:"video",goal:"Explain cell structure",userApproved:true});
 assert.equal(creative.listProjects().length,1);
 const media=creative.addAsset({projectId:project.id,type:"video_reference",title:"Clip reference",uri:"content://selected/media/1",mimeType:"video/mp4",sourceLabel:"System picker",userApproved:true});
 assert.equal(media.mimeType,"video/mp4");
 assert.throws(()=>creative.addAsset({projectId:project.id,type:"text",title:"Outline",text:"Hello"}),/approval/i);
 creative.addAsset({projectId:project.id,type:"text",title:"Outline",text:"A clear introduction",userApproved:true});
 const draft=creative.saveDraft({projectId:project.id,title:"Narration",content:"First version",userApproved:true});
 const revised=creative.saveDraft({id:draft.id,projectId:project.id,title:"Narration",content:"Revised version",userApproved:true});
 assert.equal(revised.revisions.length,1);
 assert.equal(creative.listDrafts(project.id)[0].content,"Revised version");
 assert.throws(()=>creative.restoreDraftRevision(draft.id,0),/confirmation/i);
 const restored=creative.restoreDraftRevision(draft.id,0,{confirmed:true});
 assert.equal(restored.content,"First version"); assert.equal(restored.revisions[0].content,"Revised version");
 const srt="1\n00:00:01,000 --> 00:00:02,500\nHello there\n\n2\n00:00:02,600 --> 00:00:04,000\nWelcome back";
 const cues=parseSubtitles(srt); assert.equal(cues.length,2);
 const vtt=renderSubtitles(cues,"vtt"); assert.match(vtt,/^WEBVTT/); assert.match(vtt,/00:00:01\.000 --> 00:00:02\.500/);
 const imported=creative.importSubtitles({projectId:project.id,title:"Captions",content:srt,userApproved:true});
 assert.equal(imported.cueCount,2); assert.match(creative.exportSubtitles(imported.id,"srt"),/Hello there/);
 const captionHits=creative.searchSubtitles("hello",{projectId:project.id}); assert.equal(captionHits.length,1); assert.equal(captionHits[0].title,"Captions"); assert.equal(captionHits[0].startTime,"00:00:01.000"); assert.match(captionHits[0].text,/Hello there/); assert.deepEqual(creative.searchSubtitles("missing"),[]);
 assert.throws(()=>parseSubtitles("1\n00:00:04,000 --> 00:00:02,000\nBad"),/timestamps/i);
 assert.throws(()=>creative.importSubtitles({projectId:project.id,content:srt}),/approval/i);
 const deck=creative.createDeck({title:"Cell biology",subject:"Biology",cards:[{question:"What is a cell?",answer:"Basic unit of life"},{question:"What surrounds a cell?",answer:"Cell membrane"}],userApproved:true});
 assert.equal(deck.cards.length,2);
 assert.throws(()=>creative.recordCardReview(deck.id,deck.cards[0].id,"good"),/confirmation/i);
 const reviewedCard=creative.recordCardReview(deck.id,deck.cards[0].id,"good",{confirmed:true});
 assert.equal(reviewedCard.intervalDays,3);
 assert.ok(Date.parse(reviewedCard.nextReviewAt)>Date.parse(reviewedCard.lastReviewedAt));
 assert.equal(creative.listDueFlashcards({at:"2100-01-01T00:00:00.000Z"}).length,1);
 assert.equal(creative.flashcardReviewSummary({at:"2100-01-01T00:00:00.000Z"}).dueCards,1);
 const hardReview=creative.recordCardReview(deck.id,deck.cards[0].id,"hard",{confirmed:true});
 assert.equal(hardReview.intervalDays,4);
 assert.throws(()=>creative.listDueFlashcards({at:"not-a-date"}),/valid review date/i);
 const quiz=creative.buildQuiz({title:"Cell quiz",questions:[{prompt:"What is a cell?",answer:"Basic unit of life"}],userApproved:true});
 const graded=creative.gradeQuiz(quiz,{0:"Basic unit of life"});
 assert.equal(graded.percentage,100);
 assert.throws(()=>creative.saveQuizAttempt(quiz,{0:"Basic unit of life"}),/approval/i);
 const savedAttempt=creative.saveQuizAttempt(quiz,{0:"Basic unit of life"},{userApproved:true});
 assert.equal(savedAttempt.percentage,100);
 assert.equal(creative.listQuizAttempts().length,1);
 assert.equal(creative.listQuizAttempts({subject:"biology"}).length,0);
 assert.equal(creative.quizPerformance().averagePercentage,100);
 assert.equal(creative.quizPerformance().bestPercentage,100);
 assert.equal(creative.status().quizAttemptCount,1);
 const failedQuiz=creative.buildQuiz({title:"Second quiz",subject:"Biology",questions:[{prompt:"What is a cell?",answer:"Basic unit of life"}],userApproved:true});
 creative.saveQuizAttempt(failedQuiz,{0:"wrong answer"},{userApproved:true});
 assert.equal(creative.quizPerformance({subject:"biology"}).attemptCount,1);
 assert.equal(creative.quizPerformance().averagePercentage,50);
 const insights=creative.learningInsights();
 assert.equal(insights.localOnly,true);
 assert.equal(insights.attempts,2);
 assert.equal(insights.subjects[0].subject,"Biology");
 assert.equal(insights.subjects[0].averagePercentage,0);
 assert.equal(insights.reviewTargets[0].prompt,"What is a cell?");
 assert.equal(insights.reviewTargets[0].missed,1);
 assert.equal(insights.reviewTargets[0].missRate,50);

 assert.equal(creative.search("What is a cell").some(item=>item.kind==="quiz_attempt"),true);
 const legacyValues=new Map([["aurora.creative.universe.v1",JSON.stringify({version:1,projects:[],assets:[],drafts:[],decks:[]})]]);
 const migrated=createAuroraCreativeUniverse({storage:{getItem:k=>legacyValues.get(k)??null,setItem:(k,v)=>legacyValues.set(k,v)}});
 assert.deepEqual(migrated.listQuizAttempts(),[]);

 assert.equal(creative.search("Narration")[0].kind,"draft");
 const context=creative.buildProjectContext(project.id,{maxChars:2000});
 assert.equal(context.sourceAware,true); assert.equal(context.includedSources,4); assert.match(context.text,/Project: Science explainer/); assert.match(context.text,/First version|Revised version/); assert.ok(context.text.length<=2000);
 assert.throws(()=>creative.buildProjectContext("missing"),/Project not found/i);
 assert.equal(creative.status().cloudSync,false);
 assert.throws(()=>createAuroraCreativeUniverse({storage:{getItem:()=>"broken"}}).status(),/corrupt/i);
 assert.throws(()=>creative.deleteProject(project.id),/confirmation/i);
 assert.equal(creative.deleteProject(project.id,{confirmed:true}),true);
 assert.equal(creative.listAssets(project.id).length,0);
 console.log("AURORA Stage 11 creative-universe tests passed: projects, approved assets, revisioned drafts, SRT/VTT import/export, flashcards, quiz grading, search, local-only storage and confirmed deletion.");
})().catch(error=>{console.error(error);process.exitCode=1;});
