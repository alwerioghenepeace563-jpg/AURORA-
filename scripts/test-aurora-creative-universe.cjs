const assert = require("node:assert/strict");
(async () => {
 const {createAuroraCreativeUniverse,parseSubtitles,renderSubtitles}=await import("../src/core/aurora-creative-universe.js");
 const values=new Map(),storage={getItem:k=>values.get(k)??null,setItem:(k,v)=>values.set(k,v),removeItem:k=>values.delete(k)};
 let id=0,tick=0;
 const creative=createAuroraCreativeUniverse({storage,createId:p=>p+"-"+(++id),now:()=>new Date(1762646400000+tick++*1000).toISOString()});
 assert.throws(()=>creative.createProject({title:"Short film",type:"video"}),/approval/i);
 const project=creative.createProject({title:"Science explainer",type:"video",goal:"Explain cell structure",userApproved:true});
 assert.equal(creative.listProjects().length,1);
 const media=creative.addAsset({projectId:project.id,type:"video_reference",title:"Clip reference",uri:"content://selected/media/1",mimeType:"video/mp4",sourceLabel:"System picker",userApproved:true});
 assert.equal(media.mimeType,"video/mp4");
 assert.throws(()=>creative.addAsset({projectId:project.id,type:"text",title:"Outline",text:"Hello"}),/approval/i);
 creative.addAsset({projectId:project.id,type:"text",title:"Outline",text:"A clear introduction",userApproved:true});
 const draft=creative.saveDraft({projectId:project.id,title:"Narration",content:"First version",userApproved:true});
 const revised=creative.saveDraft({id:draft.id,projectId:project.id,title:"Narration",content:"Revised version",userApproved:true});
 assert.equal(revised.revisions.length,1);
 assert.equal(creative.listDrafts(project.id)[0].content,"Revised version");
 const srt="1\n00:00:01,000 --> 00:00:02,500\nHello there\n\n2\n00:00:02,600 --> 00:00:04,000\nWelcome back";
 const cues=parseSubtitles(srt); assert.equal(cues.length,2);
 const vtt=renderSubtitles(cues,"vtt"); assert.match(vtt,/^WEBVTT/); assert.match(vtt,/00:00:01\.000 --> 00:00:02\.500/);
 const imported=creative.importSubtitles({projectId:project.id,title:"Captions",content:srt,userApproved:true});
 assert.equal(imported.cueCount,2); assert.match(creative.exportSubtitles(imported.id,"srt"),/Hello there/);
 assert.throws(()=>parseSubtitles("1\n00:00:04,000 --> 00:00:02,000\nBad"),/timestamps/i);
 assert.throws(()=>creative.importSubtitles({projectId:project.id,content:srt}),/approval/i);
 const deck=creative.createDeck({title:"Cell biology",subject:"Biology",cards:[{question:"What is a cell?",answer:"Basic unit of life"},{question:"What surrounds a cell?",answer:"Cell membrane"}],userApproved:true});
 assert.equal(deck.cards.length,2);
 assert.throws(()=>creative.recordCardReview(deck.id,deck.cards[0].id,"good"),/confirmation/i);
 creative.recordCardReview(deck.id,deck.cards[0].id,"good",{confirmed:true});
 const quiz=creative.buildQuiz({title:"Cell quiz",questions:[{prompt:"What is a cell?",answer:"Basic unit of life"}],userApproved:true});
 const graded=creative.gradeQuiz(quiz,{0:"Basic unit of life"});
 assert.equal(graded.percentage,100);
 assert.equal(creative.search("Narration")[0].kind,"draft");
 assert.equal(creative.status().cloudSync,false);
 assert.throws(()=>createAuroraCreativeUniverse({storage:{getItem:()=>"broken"}}).status(),/corrupt/i);
 assert.throws(()=>creative.deleteProject(project.id),/confirmation/i);
 assert.equal(creative.deleteProject(project.id,{confirmed:true}),true);
 assert.equal(creative.listAssets(project.id).length,0);
 console.log("AURORA Stage 11 creative-universe tests passed: projects, approved assets, revisioned drafts, SRT/VTT import/export, flashcards, quiz grading, search, local-only storage and confirmed deletion.");
})().catch(error=>{console.error(error);process.exitCode=1;});
