const assert = require("node:assert/strict");

(async () => {
  const { createAuroraKnowledgeUniverse, AURORA_KNOWLEDGE_UNIVERSE_STORAGE_KEY } = await import("../src/core/aurora-knowledge-universe.js");
  const values = new Map();
  const storage = { getItem: key => values.get(key) ?? null, setItem: (key, value) => values.set(key, value), removeItem: key => values.delete(key) };
  let id = 0, clock = 0;
  const universe = createAuroraKnowledgeUniverse({ storage, createId: () => "source-" + (++id), now: () => new Date(1762646400000 + clock++ * 1000).toISOString() });
  assert.throws(() => universe.add({ type: "note", title: "No consent", content: "Not approved" }), /approval/i);
  const first = universe.add({ type: "project", title: "AURORA core", content: "Shared intelligence connects memory, tasks and voice.", tags: ["AURORA", "architecture"], userApproved: true, sourceLabel: "User note", projectId: "aurora" });
  assert.equal(first.duplicate, false);
  assert.equal(first.record.storage, "local");
  // A matching short hash alone must never cause a false duplicate.
  const stored = JSON.parse(values.get(AURORA_KNOWLEDGE_UNIVERSE_STORAGE_KEY));
  stored.records.unshift({ ...first.record, id: "collision-decoy", title: "Different source", content: "Different content" });
  values.set(AURORA_KNOWLEDGE_UNIVERSE_STORAGE_KEY, JSON.stringify(stored));
  const longRecord = universe.add({ type: "note", title: "Long note", content: "x".repeat(12001), userApproved: true });
  assert.equal(longRecord.record.content.length, 12000);
  assert.equal(longRecord.record.contentTruncated, true);
  assert.equal(first.record.source.method, "user_selected");
  const duplicate = universe.add({ type: "project", title: "AURORA core", content: "Shared intelligence connects memory, tasks and voice.", userApproved: true });
  assert.equal(duplicate.duplicate, true);
  assert.equal(duplicate.record.id, first.record.id);
  const doc = universe.add({ type: "document", title: "Architecture decision", content: "Keep one shared brain for every AURORA surface.", userApproved: true, projectId: "aurora", uri: "https://example.com/architecture" });
  assert.throws(() => universe.add({ type: "website", title: "Bad URL", content: "x", userApproved: true, uri: "javascript:alert(1)" }), /HTTP/i);
  assert.equal(universe.search("memory connects").length, 1);
  assert.equal(universe.search("architecture", { projectId: "aurora" }).length, 2);
  assert.equal(universe.search("architecture", { types: ["document"] }).length, 1);
  assert.equal(universe.link({ from: first.record.id, to: doc.record.id, relation: "supports" }).duplicate, false);
  assert.equal(universe.link({ from: first.record.id, to: doc.record.id, relation: "supports" }).duplicate, true);
  assert.equal(universe.related(first.record.id).related[0].id, doc.record.id);
  assert.equal(universe.timeline({ projectId: "aurora" }).length, 2);
  assert.throws(() => universe.correct(first.record.id, { content: "Corrected." }), /confirmation/i);
  const corrected = universe.correct(first.record.id, { content: "Corrected shared brain architecture." }, { confirmed: true });
  assert.equal(corrected.revisions.length, 1);
  assert.equal(corrected.content, "Corrected shared brain architecture.");
  assert.throws(() => universe.remove(doc.record.id), /confirmation/i);
  assert.equal(universe.remove(doc.record.id, { confirmed: true }), true);
  assert.equal(universe.related(first.record.id).links.length, 0);
  assert.equal(universe.status().cloudSync, false);
  assert.equal(universe.status().automaticCapture, false);
  assert.equal(values.has(AURORA_KNOWLEDGE_UNIVERSE_STORAGE_KEY), true);
  assert.equal(universe.clear({ confirmed: true }), 2);
  assert.equal(universe.list().length, 0);
  console.log("AURORA Stage 9 knowledge-universe tests passed: explicit source approval, provenance, deduplication, scoped search, relationships, timeline, corrections, confirmed deletion and local-only storage.");
})().catch(error => { console.error(error); process.exitCode = 1; });
