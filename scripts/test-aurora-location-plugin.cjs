const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const read = (file) => fs.readFileSync(path.join(__dirname, "..", file), "utf8");
const plugin = read("android/app/src/main/java/com/aurora/assistant/AuroraLocationPlugin.java");
const activity = read("android/app/src/main/java/com/aurora/assistant/MainActivity.java");
const bridge = read("src/lib/aurora-native.ts");
const patcher = read("scripts/patch-android-native.mjs");
const parity = read("scripts/check-android-feature-parity.mjs");
assert.match(activity, /registerPlugin\(AuroraLocationPlugin\.class\)/);
assert.match(plugin, /name = "AuroraLocation"/);
assert.match(plugin, /requestPermissionForAlias\("location"/);
assert.match(plugin, /requestSingleUpdate/);
assert.match(plugin, /postDelayed\(timeoutRunnable, 15000L\)/);
assert.match(plugin, /age > 30000L/);
assert.match(plugin, /backgroundTracking", false/);
assert.match(plugin, /source", "one_shot_location_update"/);
assert.match(plugin, /handleOnPause/);
assert.match(plugin, /removeUpdates\(activeListener\)/);
assert.match(bridge, /registerPlugin<AuroraLocationPlugin>\("AuroraLocation"\)/);
assert.match(bridge, /return AuroraLocation\.getCurrentLocation\(\)/);
assert.match(bridge, /return AuroraLocation\.requestLocationPermission\(\)/);
assert.match(patcher, /AuroraLocationPlugin\.class/);
assert.match(patcher, /Foreground one-shot Android location plugin is missing/);
assert.match(parity, /One-shot Android location plugin registered/);
console.log("AURORA Android location plugin tests passed: foreground-only fresh fix, permission gate, timeout, stale-fix rejection and lifecycle cleanup.");
