const assert = require("node:assert/strict");
(async () => {
 const { createAuroraEventBus } = await import("../src/core/aurora-event-bus.js");
 const { createAuroraPredictiveIntelligence } = await import("../src/core/aurora-predictive-intelligence.js");
 let time = 1000000;
 const events = createAuroraEventBus({ now: () => new Date(time).toISOString() });
 const engine = createAuroraPredictiveIntelligence({ events, now: () => time });
 assert.throws(() => engine.configure({ enabled: true }), /consent/i);
 engine.configure({ enabled: true, consent: true, retentionHours: 2 });
 assert.throws(() => engine.registerSource({ id: "motion", signal: "motion", permissionGranted: true }), /consent/i);
 engine.registerSource({ id: "motion", signal: "motion", permissionGranted: true, consent: true, samplingIntervalMs: 5000 });
 assert.equal(engine.recordSignal("motion", 1).accepted, true);
 assert.equal(engine.recordSignal("motion", 0).accepted, false);
 time += 5000;
 assert.equal(engine.recordSignal("motion", 0).accepted, true);
 const item = engine.suggest({ id: "study", title: "Review your notes", reason: "You have a free study window.", sourceIds: ["motion"] });
 assert.equal(engine.listSuggestions().length, 1);
 assert.equal(engine.snooze(item.id, 60000), true);
 assert.equal(engine.listSuggestions().length, 0);
 time += 60001;
 assert.equal(engine.listSuggestions().length, 1);
 assert.equal(engine.dismiss(item.id), true);
 assert.equal(engine.listSuggestions().length, 0);
 engine.pause();
 assert.throws(() => engine.recordSignal("motion", 1), /disabled or paused/i);
 engine.resume(true);
 assert.equal(engine.getStatus().enabled, true);
 time += 2 * 60 * 60 * 1000 + 1;
 assert.equal(engine.getStatus().sampleCount, 0, "samples expire at the configured retention boundary");
 engine.unregisterSource("motion");
 assert.equal(engine.getStatus().sourceCount, 0);
 engine.clear();
 engine.configure({ enabled: false });
 assert.equal(engine.getStatus().sampleCount, 0);
 console.log("AURORA predictive intelligence tests passed.");
})().catch(error => { console.error(error); process.exitCode = 1; });
