const assert = require("node:assert/strict");
const fs = require("node:fs");
const app = fs.readFileSync("src/App.jsx", "utf8");
const chat = fs.readFileSync("api/chat.js", "utf8");
const voiceApi = fs.readFileSync("api/voice.js", "utf8");
const nativeBridge = fs.readFileSync("src/lib/aurora-native.ts", "utf8");
const nativePlugin = fs.readFileSync("android/app/src/main/java/com/aurora/assistant/AuroraAssistantPlugin.java", "utf8");

(async () => {
  const voice = await import("../src/core/aurora-voice-intelligence.js");
  assert.equal(voice.AURORA_VOICE_INTELLIGENCE.interruption, "hybrid");
  assert.equal(voice.AURORA_VOICE_INTELLIGENCE.personality, "balanced");
  assert.equal(voice.AURORA_VOICE_INTELLIGENCE.teachingMode, "adaptive");
  assert.equal(voice.AURORA_VOICE_INTELLIGENCE.speechDelivery, "adaptive");
  assert.equal(voice.normalizeSpeechText("Hello,   AURORA!"), "hello aurora");
  assert.equal(voice.isImmediateInterruptionCommand("Stop talking"), true);
  assert.equal(voice.isImmediateInterruptionCommand("repeat that"), true);
  assert.equal(voice.isImmediateInterruptionCommand("please explain photosynthesis"), false);
  assert.equal(voice.isLikelySpeechEcho("photosynthesis uses sunlight and water", "Photosynthesis uses sunlight and water to make glucose"), true);
  assert.equal(voice.isLikelySpeechEcho("wait, I have a question", "Photosynthesis uses sunlight and water to make glucose"), false);
  assert.equal(voice.inferSpeechDelivery("Congratulations, you did it!").style, "excited");
  assert.equal(voice.inferSpeechDelivery("Don't worry, take your time.").style, "reassuring");
  assert.equal(voice.inferSpeechDelivery("Important safety warning").style, "serious");
  assert.equal(voice.inferSpeechDelivery("Let's learn this step by step").style, "teaching");
  assert.ok(voice.buildVoiceIntelligenceInstructions().includes("ADAPTIVE TEACHING"));
  assert.ok(voice.buildVoiceIntelligenceInstructions().includes("balanced personality"));
  assert.ok(app.includes("startBargeInDetection"));
  assert.ok(app.includes("isLikelySpeechEcho"));
  assert.ok(app.includes("Speaking · you can interrupt"));
  assert.ok(app.includes("voiceIntelligence: AURORA_VOICE_INTELLIGENCE"));
  assert.ok(app.includes("delivery: delivery.style"));
  assert.ok(app.includes("auroraNative.speakText(makeSpeechFriendly(text), { rate:"));
  assert.ok(chat.includes("buildVoiceIntelligenceInstructions"));
  assert.ok(voiceApi.includes("deliveryPresets"));
  assert.ok(voiceApi.includes("speed: delivery.speed"));
  assert.ok(nativeBridge.includes("rate?: number; pitch?: number"));
  assert.ok(nativeBridge.includes("addSpeechPartialResultListener"));
  assert.ok(nativePlugin.includes("textToSpeech.setSpeechRate(rate)"));
  assert.ok(nativePlugin.includes("textToSpeech.setPitch(pitch)"));
  assert.ok(nativePlugin.includes("speechPartialResult"));
  assert.ok(nativePlugin.includes("EXTRA_PARTIAL_RESULTS"));
  console.log("AURORA Stage 8 voice-intelligence checks passed.");
})().catch(error => { console.error(error); process.exitCode = 1; });
